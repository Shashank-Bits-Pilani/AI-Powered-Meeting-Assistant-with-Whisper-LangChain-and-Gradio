#######------------- LLM Initialization-------------#######


# Import Ollama integration for LangChain
from langchain_ollama import ChatOllama



# Configure Llama 3.2 model parameters
parameters = {
    "temperature": 0.5,
    "top_k": 50,
    "top_p": 1.0,
    "num_predict": 512,
}

# Set the model name
model_id = "llama3.2"

# Initialize Llama 3.2 using Ollama
llama_llm = ChatOllama(
    model=model_id,
    temperature=parameters["temperature"],
    top_k=parameters["top_k"],
    top_p=parameters["top_p"],
    num_predict=parameters["num_predict"],
)




#######------------- Helper Functions-------------#######

# Function to remove non-ASCII characters
def remove_non_ascii(text):
    return ''.join(i for i in text if ord(i) < 128)


# Initialize Llama 3.2 once
llama32 = ChatOllama(
    model="llama3.2",
    temperature=0.2,
    top_p=0.6
)


def meeting_assistant(ascii_transcript):

    system_prompt = """
    You are an intelligent AI Meeting Assistant specializing
    in processing meeting transcripts generated by Whisper.

    Your task is to improve the readability and accuracy of
    meeting transcripts.

    Follow these instructions:

    1. Correct grammatical errors, punctuation, and spelling.

    2. Identify technical acronyms and expand them when
       their meanings are clear from context.

       Examples:
       - AI -> Artificial Intelligence (AI)
       - ML -> Machine Learning (ML)
       - LLM -> Large Language Model (LLM)
       - API -> Application Programming Interface (API)
       - RAG -> Retrieval-Augmented Generation (RAG)
       - NLP -> Natural Language Processing (NLP)

    3. Correct obvious speech-to-text transcription errors
       when the intended wording is clear.

    4. Preserve the original meaning of the conversation.

    5. Do not invent information, decisions, names,
       deadlines, or action items.

    6. Preserve numerical values, dates, and names.

    7. If a technical acronym has multiple possible meanings,
       determine its meaning from context. If uncertain,
       leave it unchanged.

    Return the output in this format:

    Corrected Meeting Transcript:
    [Corrected transcript]

    Changes Made:
    [List of significant corrections]
    """

    messages = [
        SystemMessage(content=system_prompt),
        HumanMessage(content=ascii_transcript)
    ]

    response = llama32.invoke(messages)

    return response.content



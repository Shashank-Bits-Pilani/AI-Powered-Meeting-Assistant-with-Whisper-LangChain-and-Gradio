#######------------- Prompt Template and Chain-------------#######

# Define the prompt template
template = """
Generate meeting minutes and a list of tasks based on the provided context.

Context:
{context}

Meeting Minutes:
- Key points discussed
- Decisions made

Task List:
- Actionable items with assignees and deadlines
"""

prompt = ChatPromptTemplate.from_template(template)

# Define the chain
chain = (
    {"context": RunnablePassthrough()}  # Pass the transcript as context
    | prompt
    | llama_llm
    | StrOutputParser()
)



#######------------- Speech2text and Pipeline-------------#######



# STEP 1: Load Whisper only once when the app starts
device = 0 if torch.cuda.is_available() else -1

pipe = pipeline(
    task="automatic-speech-recognition",
    model="openai/whisper-tiny.en",
    device=device
)

print("Whisper model loaded successfully!")


# STEP 2: Optimized speech-to-text function
def transcript_audio(audio_file):

    if audio_file is None:
        return "Please upload an audio file.", None

    start_time = time.perf_counter()

    try:
        # Transcribe audio
        raw_transcript = pipe(
            audio_file,
            return_timestamps=True
        )["text"]

        transcription_time = time.perf_counter()

        # Clean transcript
        ascii_transcript = remove_non_ascii(
            raw_transcript
        )

        # Correct transcript using Llama
        adjusted_transcript = meeting_assistant(
            ascii_transcript
        )

        correction_time = time.perf_counter()

        # Generate meeting minutes and action items
        result = chain.invoke({
            "context": adjusted_transcript
        })

        # Handle LangChain string or AIMessage output
        if hasattr(result, "content"):
            result = result.content
        else:
            result = str(result)

        summary_time = time.perf_counter()

        # Create a unique downloadable text file
        with tempfile.NamedTemporaryFile(
            mode="w",
            suffix=".txt",
            prefix="meeting_minutes_",
            encoding="utf-8",
            delete=False
        ) as file:
            file.write(result)
            output_file = file.name

        # Display performance measurements
        print(
            f"Whisper transcription: "
            f"{transcription_time - start_time:.2f}s"
        )

        print(
            f"Llama transcript correction: "
            f"{correction_time - transcription_time:.2f}s"
        )

        print(
            f"Llama meeting summary: "
            f"{summary_time - correction_time:.2f}s"
        )

        print(
            f"Total processing: "
            f"{time.perf_counter() - start_time:.2f}s"
        )

        return result, output_file

    except Exception as e:
        print(f"Meeting processing error: {e}")
        return f"Error: {e}", None



#######------------- Gradio Interface-------------#######

audio_input = gr.Audio(sources="upload", type="filepath", label="Upload your audio file")
output_text = gr.Textbox(label="Meeting Minutes and Tasks")
download_file = gr.File(label="Download the Generated Meeting Minutes and Tasks")

iface = gr.Interface(
    fn=transcript_audio,
    inputs=audio_input,
    outputs=[output_text, download_file],
    title="AI Meeting Assistant",
    description="Upload an audio file of a meeting. This tool will transcribe the audio, fix product-related terminology, and generate meeting minutes along with a list of tasks."
)

if __name__ == "__main__":
    iface.launch(
        server_name="127.0.0.1",
        server_port=7860,
        share=False,
        show_error=True
    )

